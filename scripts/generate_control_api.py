#!/usr/bin/env python3
"""Generate official typed IAM/STS model bridges from pinned Apache-2.0 SDK shapes."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generate(service,model):
    ns='IAM' if service=='iam' else 'STS'
    shapes=model['shapes'];ops=model['operations']
    outputs={o['output']['shape'] for o in ops.values() if 'output' in o}
    usable={n:s for n,s in shapes.items() if n not in outputs}
    def cname(n):return n[0].upper()+n[1:]
    def cpp(n):
        s=shapes[n];t=s['type']
        if t=='structure' or 'enum' in s:return 'Aws::'+ns+'::Model::'+cname(n)
        if t=='list':return 'Aws::Vector<'+cpp(s['member']['shape'])+'>'
        if t=='map':return 'Aws::Map<'+cpp(s['key']['shape'])+','+cpp(s['value']['shape'])+'>'
        return {'string':'Aws::String','integer':'int','long':'int64_t','boolean':'bool','timestamp':'Aws::Utils::DateTime','double':'double','float':'double'}[t]
    def rd(n,v):return 'read_'+n+'('+v+')'
    def wr(n,v):return 'write_'+n+'('+v+')'
    lines=['// Generated by scripts/generate_control_api.py; do not edit.', '// Model provenance/license: drivers/schema/control-api.json.','#pragma once','#include <set>','#include <limits>','#include <aws/'+service+'/'+ns+'Client.h>']
    for n,s in usable.items():
        if s['type']=='structure' or 'enum' in s:lines.append('#include <aws/'+service+'/model/'+cname(n)+'.h>')
    for name,o in ops.items():
        if 'output' in o:lines.append('#include <aws/'+service+'/model/'+name+'Result.h>')
    lines+=['namespace osv_control_'+service+' {','using J=nlohmann::json;']
    for n in usable:lines+=['inline '+cpp(n)+' read_'+n+'(const J& value);','inline J write_'+n+'(const '+cpp(n)+'& value);']
    for n,s in usable.items():
        t=s['type'];ct=cpp(n);lines+=['inline '+ct+' read_'+n+'(const J& value){']
        if 'enum' in s:
            lines+=[' if(!value.is_string())throw std::runtime_error("SDK enum must be text: '+n+'");',' return Aws::'+ns+'::Model::'+cname(n)+'Mapper::Get'+cname(n)+'ForName(value.get<std::string>());']
        elif t=='structure':
            members=s.get('members',{});lines+=[' if(!value.is_object())throw std::runtime_error("SDK structure must be an object: '+n+'");',' static const std::set<std::string> allowed={'+','.join(json.dumps(k) for k in members)+'};',' for(auto it=value.begin();it!=value.end();++it)if(!allowed.count(it.key()))throw std::runtime_error("SDK model has no member: "+it.key());',ct+' result;']
            for f,m in members.items():lines+=[' if(value.contains("'+f+'") && !value.at("'+f+'").is_null())result.Set'+cname(f)+'('+rd(m['shape'],'value.at("'+f+'")')+');']
            lines+=[' return result;']
        elif t=='list':lines+=[' if(!value.is_array())throw std::runtime_error("SDK list must be an array: '+n+'");',ct+' result;for(const auto& v:value)result.push_back('+rd(s['member']['shape'],'v')+');return result;']
        elif t=='map':lines+=[' if(!value.is_object())throw std::runtime_error("SDK map must be an object: '+n+'");',ct+' result;for(auto it=value.begin();it!=value.end();++it)result['+rd(s['key']['shape'],'J(it.key())')+']='+rd(s['value']['shape'],'it.value()')+';return result;']
        elif t in ('integer','long'):lines+=[' return static_cast<'+ct+'>(osv_control_api::integer(value,std::numeric_limits<'+ct+'>::min(),std::numeric_limits<'+ct+'>::max()));']
        elif t=='timestamp':lines+=[' if(!value.is_number_integer())throw std::runtime_error("SDK timestamp must be epoch milliseconds");',' return Aws::Utils::DateTime(osv_control_api::integer(value,std::numeric_limits<int64_t>::min(),std::numeric_limits<int64_t>::max()));']
        else:
            check={'string':'is_string','boolean':'is_boolean','double':'is_number','float':'is_number'}[t];get='std::string' if t=='string' else ct
            lines+=[' if(!value.'+check+'())throw std::runtime_error("SDK '+t+' type required: '+n+'");',' return value.get<'+get+'>();']
        lines+=['}','inline J write_'+n+'(const '+ct+'& value){']
        if 'enum' in s:lines+=[' return std::string(Aws::'+ns+'::Model::'+cname(n)+'Mapper::GetNameFor'+cname(n)+'(value).c_str());']
        elif t=='structure':
            lines+=[' J result=J::object();']
            for f,m in s.get('members',{}).items():
                v=wr(m['shape'],'value.Get'+cname(f)+'()')
                if f in ('PolicyDocument','AssumeRolePolicyDocument'):v='osv_control_api::policy('+v+')'
                lines+=[' if(value.'+cname(f)+'HasBeenSet())result["'+f+'"]='+v+';']
            lines+=[' return result;']
        elif t=='list':lines+=[' J result=J::array();for(const auto& v:value)result.push_back('+wr(s['member']['shape'],'v')+');return result;']
        elif t=='map':lines+=[' J result=J::object();for(const auto& v:value)result['+wr(s['key']['shape'],'v.first')+'.get<std::string>()]='+wr(s['value']['shape'],'v.second')+';return result;']
        elif t=='timestamp':lines+=[' return value.Millis();']
        elif t=='string':lines+=[' return std::string(value.c_str());']
        else:lines+=[' return value;']
        lines+=['}']
    lines+=['inline const std::vector<std::string>& operations(){static const std::vector<std::string> value={'+','.join(json.dumps('api.'+service+'.'+n) for n in ops)+'};return value;}', 'inline J execute(Aws::'+ns+'::'+ns+'Client& client,const J& q){',' const std::string op=q.at("op");const J& input=q.at("input");',' if(!input.is_object())throw std::runtime_error("api input must be an object");']
    for name,o in ops.items():
        lines+=[' if(op=="api.'+service+'.'+name+'"){',' auto request=read_'+o['input']['shape']+'(input);J observed;HttpObservationScope observation(&observed,true);',' auto outcome=client.'+name+'(request);checked(outcome);',' if(!observed.contains("status_code"))throw std::runtime_error("SDK HTTP observation unavailable");',' J data=J::object();']
        if 'output' in o:
            output=o['output'];wrapper=output.get('resultWrapper',name+'Result');lines+=[' const auto& result=outcome.GetResult();']
            for f,m in shapes[output['shape']].get('members',{}).items():
                key=m.get('locationName',f);v=wr(m['shape'],'result.Get'+cname(f)+'()')
                if f in ('PolicyDocument','AssumeRolePolicyDocument'):v='osv_control_api::policy('+v+')'
                lines+=[' if(osv_control_api::present(observed,"'+wrapper+'","'+key+'"))data["'+f+'"]='+v+';']
        lines+=[' observed["data"]=data;observed.erase("fields");observed.erase("result_fields");observed.erase("xml_root");return observed;',' }']
    lines+=[' throw std::runtime_error("unsupported control operation");','}','}']
    return '\n'.join(lines)+'\n'

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();m=json.loads((ROOT/'drivers/schema/control-api.json').read_text())
    artifacts={ROOT/f'drivers/cpp/control_{s}_generated.h':generate(s,v) for s,v in m.items()}
    operations={s:list(v['operations']) for s,v in m.items()}
    java='package io.github.storagevalidation;\nimport java.util.*;\n/** Shares the pinned official SDK operation allowlist across control-plane bridges. Generates explicit service lists to prevent unsupported API dispatch. */\nfinal class ControlApiOperations {\n'
    for s,names in operations.items():java+=' static final List<String> '+s.upper()+'=List.of('+','.join(json.dumps(n) for n in names)+');\n'
    java+='}\n';artifacts[ROOT/'drivers/java/src/main/java/io/github/storagevalidation/ControlApiOperations.java']=java
    for path,content in artifacts.items():
        if a.check:
            if not path.exists() or path.read_text()!=content:p.exit(1,'generated control API differs: '+str(path)+'\n')
        else:path.write_text(content)
if __name__=='__main__':main()
