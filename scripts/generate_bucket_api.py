#!/usr/bin/env python3
"""Generate typed C++ SDK model converters and a shared Java bucket-API allowlist."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def generate(model):
    operations=model["operations"]
    # Service error shapes are handled by actual SDK outcomes, not generated model classes.
    # Some AWS error names deliberately have no C++ public model header.
    reachable=set()
    def include(name):
        if name in reachable:return
        reachable.add(name)
        def references(value):
            if isinstance(value,dict):
                if "shape" in value:include(value["shape"])
                for item in value.values():references(item)
            elif isinstance(value,list):
                for item in value:references(item)
        references(model["shapes"][name])
    for operation in operations.values():
        for direction in ("input","output"):
            if direction in operation:include(operation[direction]["shape"])
    shapes={name:shape for name,shape in model["shapes"].items() if name in reachable}
    outputs={operation["output"]["shape"] for operation in operations.values() if "output" in operation}
    reusable=[name for name in shapes if name not in outputs]

    def cpp(name):
        shape=shapes[name];kind=shape["type"]
        if kind=="structure" or "enum" in shape:return "Aws::S3::Model::"+shape.get("cpp_name",name)
        if kind=="string":return "Aws::String"
        if kind=="integer":return "int"
        if kind=="long":return "int64_t"
        if kind=="boolean":return "bool"
        if kind in ("float","double"):return "double"
        if kind=="timestamp":return "Aws::Utils::DateTime"
        if kind=="list":return "Aws::Vector<"+cpp(shape["member"]["shape"])+">"
        if kind=="map":return "Aws::Map<Aws::String,"+cpp(shape["value"]["shape"])+">"
        raise ValueError("unsupported SDK shape: "+name+" "+kind)

    lines=["// Generated by scripts/generate_bucket_api.py; do not edit by hand.",
           "// API model provenance and Apache-2.0 notice: drivers/schema/bucket-api.json.",
           "#pragma once","#include <set>","#include <limits>"]
    for name in reusable:
        if shapes[name]["type"]=="structure" or "enum" in shapes[name]:lines.append("#include <aws/s3/model/"+shapes[name].get("cpp_name",name)+".h>")
    for name,operation in operations.items():
        if "output" in operation:lines.append("#include <aws/s3/model/"+name+"Result.h>")
    lines.extend(["namespace osv_bucket_api {","using J=nlohmann::json;",
                  "inline int64_t signed_integer(const J& value,int64_t minimum,int64_t maximum,const char* field){",
                  "    if(!value.is_number_integer())throw std::runtime_error(std::string(\"SDK integer must be integral: \")+field);",
                  "    if(value.is_number_unsigned()){auto number=value.get<uint64_t>();if(number>static_cast<uint64_t>(maximum))throw std::runtime_error(std::string(\"SDK integer outside range: \")+field);return static_cast<int64_t>(number);}",
                  "    auto number=value.get<int64_t>();if(number<minimum || number>maximum)throw std::runtime_error(std::string(\"SDK integer outside range: \")+field);return number;",
                  "}"])
    for name in reusable:
        lines.extend(["inline "+cpp(name)+" read_"+name+"(const J& value);","inline J write_"+name+"(const "+cpp(name)+"& value);"])
    for name in reusable:
        shape=shapes[name];kind=shape["type"];ctype=cpp(name)
        lines.append("inline "+ctype+" read_"+name+"(const J& value) {")
        if "enum" in shape:
            lines.append("    return Aws::S3::Model::"+name+"Mapper::Get"+name+"ForName(value.get<std::string>());")
        elif kind=="structure":
            members={field:member for field,member in shape.get("members",{}).items() if not member.get("deprecated",False)}
            lines.extend(["    if(!value.is_object())throw std::runtime_error(\"SDK structure must be an object: "+name+"\");",
                          "    static const std::set<std::string> allowed={"+",".join(json.dumps(field) for field in members)+"};",
                          "    for(auto it=value.begin();it!=value.end();++it)if(!allowed.count(it.key()))throw std::runtime_error(\"SDK model has no member: \"+it.key());", "    "+ctype+" result;"])
            for field,member in members.items():
                if field==shape.get("cpp_streaming_payload"):
                    lines.append("    if(value.contains(\""+field+"\")){auto stream=Aws::MakeShared<Aws::StringStream>(\"osv-api-payload\");*stream<<value.at(\""+field+"\").get<std::string>();result.SetBody(stream);result.SetContentType(\"application/json\");}")
                else:lines.append("    if(value.contains(\""+field+"\") && !value.at(\""+field+"\").is_null())result.Set"+field+"(read_"+member["shape"]+"(value.at(\""+field+"\")));")
            lines.append("    return result;")
        elif kind=="list":
            lines.extend(["    if(!value.is_array())throw std::runtime_error(\"SDK list must be an array: "+name+"\");", "    "+ctype+" result;for(const auto& item:value)result.push_back(read_"+shape["member"]["shape"]+"(item));return result;"])
        elif kind=="map":
            lines.extend(["    if(!value.is_object())throw std::runtime_error(\"SDK map must be an object: "+name+"\");", "    "+ctype+" result;for(auto it=value.begin();it!=value.end();++it)result[it.key()]=read_"+shape["value"]["shape"]+"(it.value());return result;"])
        elif kind=="timestamp":
            lines.append("    return value.is_number_integer()?Aws::Utils::DateTime(signed_integer(value,std::numeric_limits<int64_t>::min(),std::numeric_limits<int64_t>::max(),\""+name+"\")):Aws::Utils::DateTime(value.get<std::string>(),Aws::Utils::DateFormat::ISO_8601);")
        elif kind in ("integer","long"):
            lines.append("    return static_cast<"+ctype+">(signed_integer(value,std::numeric_limits<"+ctype+">::min(),std::numeric_limits<"+ctype+">::max(),\""+name+"\"));")
        else:
            convert="std::string" if kind=="string" else ctype
            lines.append("    return value.get<"+convert+">();")
        lines.append("}")
        lines.append("inline J write_"+name+"(const "+ctype+"& value) {")
        if "enum" in shape:lines.append("    return std::string(Aws::S3::Model::"+name+"Mapper::GetNameFor"+name+"(value).c_str());")
        elif kind=="structure":
            lines.append("    J result=J::object();")
            for field,member in shape.get("members",{}).items():
                if member.get("deprecated",False) or field==shape.get("cpp_streaming_payload"):continue
                lines.append("    if(value."+field+"HasBeenSet())result[\""+field+"\"]=write_"+member["shape"]+"(value.Get"+field+"());")
            lines.append("    return result;")
        elif kind=="list":lines.append("    J result=J::array();for(const auto& item:value)result.push_back(write_"+shape["member"]["shape"]+"(item));return result;")
        elif kind=="map":lines.append("    J result=J::object();for(const auto& item:value)result[std::string(item.first.c_str())]=write_"+shape["value"]["shape"]+"(item.second);return result;")
        elif kind=="timestamp":lines.append("    return value.Millis();")
        elif kind=="string":lines.append("    return std::string(value.c_str());")
        else:lines.append("    return value;")
        lines.append("}")

    quoted=",".join(json.dumps("api."+name) for name in operations)
    lines.extend(["inline J capabilities(){return J::array({"+quoted+"});}",
                  "inline bool handles(const std::string& op){static const std::set<std::string> allowed={"+quoted+"};return allowed.count(op)!=0;}",
                  "inline J execute(Aws::S3::S3Client& client,const J& q){",
                  "    const std::string op=q.at(\"op\");J input=q.at(\"input\");",
                  "    if(!input.is_object())throw std::runtime_error(\"api input must be a JSON object\");",
                  "    if(q.contains(\"bucket\")){if(input.contains(\"Bucket\") && input[\"Bucket\"]!=q[\"bucket\"])throw std::runtime_error(\"cannot override scoped API bucket\");input[\"Bucket\"]=q[\"bucket\"];}"])
    for name,operation in operations.items():
        output=shapes[operation["output"]["shape"]] if "output" in operation else None
        payload=output.get("payload") if output else None
        body_members={field:member for field,member in output.get("members",{}).items() if member.get("location","body")=="body"} if output else {}
        raw_payload=payload and shapes[output["members"][payload]["shape"]]["type"] in ("string","blob")
        capture=bool(body_members) and not raw_payload
        lines.extend(["    if(op==\"api."+name+"\"){",
                      "        auto request=read_"+operation["input"]["shape"]+"(input);J observed;HttpObservationScope observation(&observed,"+("true" if capture else "false")+");",
                      "        auto outcome=client."+name+"(request);checked(outcome);",
                      "        if(!observed.contains(\"status_code\"))throw std::runtime_error(\"SDK HTTP observation unavailable\");",
                      "        J data=J::object();"])
        if output:
            lines.append("        const auto& result=outcome.GetResult();")
            for field,member in output.get("members",{}).items():
                location=member.get("location","body");key=member.get("locationName",field)
                if field==payload:condition="true"
                elif location=="header":condition="observed[\"http_headers\"].contains(\""+key.lower()+"\")"
                elif location=="headers":condition="true"
                else:condition="observed.contains(\"fields\") && std::find(observed[\"fields\"].begin(),observed[\"fields\"].end(),J(\""+key+"\"))!=observed[\"fields\"].end()"
                if field==output.get("cpp_streaming_payload"):
                    lines.append("        {std::ostringstream body;body<<result.Get"+field+"().rdbuf();if(result.Get"+field+"().bad())throw std::runtime_error(\"SDK response stream failed\");data[\""+field+"\"]=body.str();}")
                else:lines.append("        if("+condition+")data[\""+field+"\"]=write_"+member["shape"]+"(result.Get"+member.get("cpp_getter",field)+"());")
        lines.extend(["        observed[\"data\"]=data;return observed;","    }"])
    lines.extend(["    throw std::runtime_error(\"unsupported bucket API: \"+op);","}","}",""])
    java="""package io.github.storagevalidation;
import java.util.*;
/**
 * Prevents the Java and generated C++ bucket API allowlists from drifting.
 * The pinned API-model generator emits the same explicit operation list for both.
 */
final class BucketApiOperations {
    static final List<String> APIS=Collections.unmodifiableList(Arrays.asList(
        """+",\n        ".join(json.dumps(name) for name in operations)+"));\n    static final Map<String,String> JAVA_BINDINGS=Map.ofEntries("+",".join("Map.entry("+json.dumps(name)+","+json.dumps(operation.get("java_api",name))+")" for name,operation in operations.items())+");\n}\n"
    return "\n".join(lines),java

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model",type=Path,default=ROOT/"drivers/schema/bucket-api.json")
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args()
    cpp,java=generate(json.loads(args.model.read_text()))
    artifacts={ROOT/"drivers/cpp/bucket_api_generated.h":cpp,ROOT/"drivers/java/src/main/java/io/github/storagevalidation/BucketApiOperations.java":java}
    for path,content in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text()!=content:parser.exit(1,"generated SDK model artifact differs: "+str(path)+"\n")
        else:path.write_text(content)

if __name__=="__main__":main()
